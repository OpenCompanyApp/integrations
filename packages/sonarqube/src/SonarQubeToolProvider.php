    /**
     * Test SonarQube bearer token credentials against authentication validation.
     *
     * @param  array<string, mixed>  $config  Credential and endpoint settings.
     * @return array{success: bool, message?: string, error?: string}
     */
    public function testConnection(array $config): array
    {
        $token = (string) ($config['api_token'] ?? '');
        $baseUrl = rtrim((string) ($config['url'] ?? 'https://next.sonarqube.com/sonarqube'), '/');
        if ($token === '') { return ['success' => false, 'error' => 'SonarQube user token is required.']; }

        try {
            $response = Http::withHeaders(['Authorization' => 'Bearer '.$token, 'Accept' => 'application/json'])->timeout(10)->get($baseUrl.'/api/authentication/validate');
            if (! $response->successful()) { return ['success' => false, 'error' => 'SonarQube API returned HTTP '.$response->status().'.']; }
            $valid = $response->json('valid');
            if ($valid === false) { return ['success' => false, 'error' => 'SonarQube token was rejected.']; }
            return ['success' => true, 'message' => 'Connected to SonarQube at '.$baseUrl.'.'];
        } catch (\Throwable $e) { return ['success' => false, 'error' => $e->getMessage()]; }
    }

