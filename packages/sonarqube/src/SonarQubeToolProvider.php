    /** Create an endpoint-specific SonarQube tool. */
    public function createTool(string $class, array $context = []): Tool
    {
        return new $class($this->resolveService($context));
    }

    public function scriptDocsPath(): ?string { return __DIR__.'/../script-docs/sonarqube.md'; }

    /**
     * Resolve default or account-specific SonarQube service credentials.
     *
     * @param  array<string, mixed>  $context  Runtime account context.
     */
    private function resolveService(array $context = []): SonarQubeService
    {
        $account = $context['account'] ?? null;
        if ($account !== null) {
            $creds = app(CredentialResolver::class);
            return new SonarQubeService(
                apiToken: $creds->get('sonarqube', 'api_token', '', $account),
                baseUrl: $creds->get('sonarqube', 'url', 'https://next.sonarqube.com/sonarqube', $account),
            );
        }

        return app(SonarQubeService::class);
    }
